// Write DIALOGUE.md (in the current directory, or --out): every line of dialogue in one place, for reading and review. Generated; edit the
// sources (bosses.ts, story.ts, hints.ts) instead.
//   node scripts/dialogue.ts --rom ROM
// Sections: the comedic lines (option "Story Dialogue": boss taunts and the replies when a boss dies, the three endings with their
// cockpit scenes, Hal), every message a sample seed rewrites (story, hints), and the whole vanilla script.

import { readFileSync, writeFileSync } from 'node:fs';
import { parseArgs } from 'node:util';
import {
  COMMANDER,
  CYBORG,
  ENDINGS,
  ESCAPE_RADIOS,
  JOE_LETTERS,
  JOE_RESCUES,
  JOE_GONE,
  JOE_HERE,
  MUSTACHE,
  POOLS,
  MISSION_REPORTS,
  ROBOT,
  SELF_DESTRUCTS,
  STILL_INSIDES,
} from '../src/core/bosses.ts';
import { generate } from '../src/core/generate.ts';
import {
  NONSENSE,
  NONSENSE_BOMBER,
  NONSENSE_BRIEFINGS,
  NONSENSE_QUESTIONS,
  NONSENSE_STATIC,
} from '../src/core/nonsense.ts';
import { makeSeedCode } from '../src/core/settings.ts';
import { readMessage } from '../src/core/text.ts';
import { unzipRom } from '../src/core/zip.ts';

const { values } = parseArgs({ options: { rom: { type: 'string' }, out: { type: 'string' } } });
if (!values.rom) {
  console.error('usage: node scripts/dialogue.ts --rom ROM [--out DIALOGUE.md]');
  process.exit(2);
}
const vanilla = (await unzipRom(new Uint8Array(readFileSync(values.rom)))).data;

/** Close-up portraits by a header's low nibble (the box style is bits 7-6). */
const PORTRAIT: Record<number, string> = {
  0x0: '(no portrait)',
  0x1: 'enemy (mustache)',
  0x2: 'enemy (cyborg/officer)',
  0x3: 'Ladd',
  0x4: 'Super Joe',
  0x5: 'enemy soldier',
  0x6: 'ally (Hal, agents)',
  0x7: 'neutral-zone man',
  0x8: 'HQ',
  0x9: 'enemy commander',
  0xa: 'Killt',
  0xe: 'Master-D',
};
const who = (header: number) => PORTRAIT[header & 0x0f] ?? `portrait $${(header & 0x0f).toString(16).toUpperCase()}`;
/** The game's 16-column rows, joined back into readable text. */
const rows = (text: string) =>
  (text.match(/.{1,16}/g) ?? [])
    .map((r) => r.trimEnd())
    .filter((r, i, a) => r || (i > 0 && i < a.length - 1))
    .join(' / ')
    .replaceAll('***', '…');
const quote = (t: string) =>
  t.replaceAll('***', '…').replaceAll('\f', ' ⏎ ').replaceAll('\n\n', ' // ').replaceAll('\n', ' / ');

const md: string[] = [
  '# Bionic Comrando dialogue',
  '',
  "Generated by `node scripts/dialogue.ts --rom ROM`; edit the sources, not this file. `/` is a line break, `//` an empty line between, `⏎` a new page (A to go on), `…` the game's three dots.",
  '',
];

md.push(
  '## Comedic lines (option "Story Dialogue": Comedic)',
  '',
  '### Boss taunts, by portrait',
  '',
  "Each boss with a generic vanilla taunt gets one line from its portrait's pool (humans borrow from each other once theirs run out). Sometimes there is a reply from Ladd or the boss when the boss is killed. There are dedicated lines for when it's the area Joe was relocated from or is present in.",
  '',
);
const POOL_NAMES: [number, string, string][] = [
  [COMMANDER, 'Commander', 'commander'],
  [ROBOT, 'Robot (no portrait)', 'robot'],
  [CYBORG, 'Cyborg', 'cyborg'],
  [MUSTACHE, 'Mustache', 'mustache'],
];
for (const [h, name, boss] of POOL_NAMES) {
  md.push(`**${name}**`, '');
  for (const line of POOLS[h]) {
    const [taunt, reply, by] = typeof line === 'string' ? [line] : line;
    md.push(
      `- ${quote(taunt)}${reply ? `\n  - *${by ? boss[0].toUpperCase() + boss.slice(1) : 'Ladd'}, when ${boss} dies:* ${quote(reply)}` : ''}`,
    );
  }
  md.push(
    '',
    'Joe relocated versions:',
    ...JOE_GONE[h].map((l) => `- ${quote(l)}`),
    '',
    'Joe present versions:',
    ...JOE_HERE[h].map((l) => `- ${quote(l)}`),
    '',
  );
}
md.push(
  '### Endings',
  '',
  'One per seed. The final scene (Killt until he dies, then Master-D), then the cockpit scene after the chopper.',
  '',
);
const NAME = { killt: 'Killt', masterD: 'Master-D', ladd: 'Ladd', hal: 'Hal' };
for (const e of ENDINGS) {
  md.push(`**${e.name}**`, '');
  for (const [s, l] of e.killt) md.push(`- ${NAME[s]}: ${quote(l)}`);
  md.push('- *(Killt dies; Master-D rises)*');
  for (const [s, l] of e.masterD) md.push(`- ${NAME[s]}: ${quote(l)}`);
  e.hal.forEach((l) => md.push(`- *Hal, in Area 12${e.hal.length > 1 ? ` (1 in ${e.hal.length})` : ''}:* ${quote(l)}`));
  const total = e.cockpit.reduce((n, c) => n + c.weight, 0);
  e.cockpit.forEach((c, i) => {
    md.push(`- *Cockpit${e.cockpit.length > 1 ? ` (${c.weight} in ${total})` : ''}:*`);
    for (const [s, l] of c.lines) md.push(`  - ${NAME[s]}: ${quote(l)}`);
    if (i === e.cockpit.length - 1) md.push('');
  });
}

md.push(
  "### Joe's rescue",
  '',
  "One per seed: Joe's answer to Ladd's \"MR.JOE. I'VE COME TO RESCUE YOU.\" (#109), instead of his speech (#109, #46, #110); his tip (#47) still follows, unless Routing Hints are Nonsense.",
  '',
  ...JOE_RESCUES.map((l) => `- ${quote(l)}`),
  '',
);
md.push(
  '### Self-destruct warnings',
  '',
  'One per seed, after Master-D (#107).',
  '',
  ...SELF_DESTRUCTS.map((l) => `- ${quote(l)}`),
  '',
);
md.push(
  '### Outside the base',
  '',
  'One per seed: Ladd\'s "IS JOE STILL INSIDE?" (#124) after the escape.',
  '',
  ...STILL_INSIDES.map((l) => `- ${quote(l)}`),
  '',
);
md.push(
  '### Escape radio',
  '',
  'One per seed: HQ and the officer on the radio after the escape ("WHAT HAPPENED TO THE CAPTAIN?", #128/#129), taking turns, HQ first.',
  '',
  ...ESCAPE_RADIOS.map((c) => c.map((l, i) => `${i ? '  ' : ''}- ${i % 2 ? 'Officer' : 'HQ'}: ${quote(l)}`).join('\n')),
  '',
);
md.push(
  '### Mission report',
  '',
  'One per seed: Ladd\'s "THIS IS LADD, OUR MISSION ACCOMPLISHED" (#7) from the chopper, as other games\' endings.',
  '',
  ...MISSION_REPORTS.map((l) => `- ${quote(l)}`),
  '',
);
md.push(
  "### Joe's letter",
  '',
  "One per seed: Joe's scrolling letter before his signature (#37).",
  '',
  ...JOE_LETTERS.map((l) => `- ${quote(l)}`),
  '',
);
md.push(
  '## Nonsense pools (Routing Hints: Nonsense)',
  '',
  "Every comm room (COMMUNICATE, wiretaps; Area 1's briefing and Area 12's rooms too) says a radio line, and so does Joe when rescued; every NZ talker and guard says a talker line (not their doors' contents), and so do Killt when he visits a neutral zone (his grunt still announces him) and the other characters' one-off lines (building soldiers, the passage room's interrogation, Captain Mack), and the intro briefing is one of its own. With Story Dialogue Vanilla, every boss says a talker line too. A seed uses a few radio lines, repeated: bank 0B fits only so many long ones.",
  '',
);
for (const [k, name] of [
  ['radio', 'Comm rooms (radio)'],
  ['talker', 'NZ talkers'],
] as const)
  md.push(
    `**${name}**`,
    '',
    ...(NONSENSE[k].length ? NONSENSE[k].map((l) => `- ${quote(l)}`) : ['- *(none yet)*']),
    '',
  );
md.push(
  '**NZ19 bombardier** (in its door-B room, instead of "GO AHEAD, SHOOT ME!")',
  '',
  ...NONSENSE_BOMBER.map((l) => `- ${quote(l)}`),
  '',
);
md.push('**Destroyers** (a question each, then YES/NO)', '', ...NONSENSE_QUESTIONS.map((l) => `- ${quote(l)}`), '');
md.push('**Wrong communicator** (instead of the static)', '', `- ${quote(NONSENSE_STATIC)}`, '');
md.push(
  '**Intro briefing** (two messages: a new one reconnects the radio)',
  '',
  ...NONSENSE_BRIEFINGS.map((b) =>
    b.map(([s, l], i) => `${i ? '  ' : ''}- ${s === 'hq' ? 'HQ' : 'Officer'}: ${quote(l)}`).join('\n'),
  ),
  '',
);

// A sample seed: every bank 0B message it rewrites (story, hints; the comedic lines above are extra texts, not listed)
const seed = makeSeedCode({}, 1n);
const { rom, spoiler } = generate(vanilla, seed, { cosmeticSeed: 'x' });
md.push(
  `## Rewritten for a sample seed (${seed}, default settings)`,
  '',
  "Story lines and hints change with every seed; this is one seed's set (its spoiler log names where each hint sits).",
  '',
);
for (let n = 2; n <= 129; n++) {
  const a = readMessage(vanilla, n),
    b = readMessage(rom, n);
  if (!a || !b || a.text === b.text || !b.text.trim()) continue;
  md.push(`- **#${n}** ${who(b.header)}: ${rows(b.text)}`);
}
md.push('', `Spoiler hints for this seed: ${spoiler.hints.length} slots.`, '');

md.push(
  '## Vanilla script',
  '',
  'Every message in the original game (bank 0B), by message number (Y = 2 × (n − 2)).',
  '',
);
for (let n = 2; n <= 129; n++) {
  const m = readMessage(vanilla, n);
  if (!m?.text.trim()) continue;
  md.push(
    `- **#${n}** ($${(2 * (n - 2)).toString(16).toUpperCase().padStart(2, '0')}) ${who(m.header)}: ${rows(m.text)}`,
  );
}
md.push('');
const out = values.out ?? 'DIALOGUE.md';
writeFileSync(out, md.join('\n'));
console.log(`wrote ${out}`);
